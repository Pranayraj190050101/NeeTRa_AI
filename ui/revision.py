"""Revision Hub tab - flash notes, formula sheets, high yield, last minute.

Four deliverables over the same RAG pipeline, plus the loop-closer: a sheet
built from the topics recorded as weak in the progress store.  The content is
generated by :class:`learning.revision.RevisionService`; this module only picks
the parameters and renders the result.
"""

from __future__ import annotations

from typing import Any, Mapping

from learning.catalog import ChapterCatalog
from learning.service import GeniePlatform
from ui.components import (
    citations_md,
    esc,
    refresh,
    subject_choices,
    table,
    weak_areas_md,
)
from utils.constants import RevisionDeliverable
from learning.sections import REVISION_SECTIONS, format_section_contract

__all__ = [
    "build",
    "deliverable_choices",
    "revision_intro_md",
    "sheet_md",
    "target_choices",
    "weak_preview_md",
    "wire",
]


def deliverable_choices() -> list[tuple[str, str]]:
    return RevisionDeliverable.ui_choices()


def revision_intro_md() -> str:
    """What each sheet is for and which sections it always has."""
    rows = [
        (
            f"{item.emoji} {item.label}",
            item.description,
            format_section_contract(REVISION_SECTIONS[item]).replace("\n", " · "),
        )
        for item in RevisionDeliverable
    ]
    return "\n".join(
        [
            "### \U0001f501 Revision Hub - dense sheets from your own books",
            "",
            table(("Sheet", "Use it when", "Sections"), rows),
            "",
            "A sheet cites the indexed passage it came from, so a line you cannot find in "
            "your own material is marked instead of invented.",
        ]
    )


def target_choices(catalog: ChapterCatalog, subject: str | None) -> list[tuple[str, str]]:
    """Revision targets: the chapters of one subject, then its raw source names."""
    chapters = [chapter.name for chapter in catalog.list(subject)]
    if not chapters:
        return []
    return [(name, name) for name in chapters]


def sheet_md(doc: Any, *, label: str = "") -> str:
    """Render one generated revision sheet."""
    if doc is None:
        return "_No sheet generated yet._"
    if not getattr(doc, "ok", True):
        return esc(doc.markdown) or "**Generation failed.**"
    head = f"_{label}_\n\n" if label else ""
    notes = "\n\n".join(f"- {esc(notice)}" for notice in doc.notices if esc(notice))
    body = f"## {esc(doc.title)}\n\n{doc.markdown}"
    return head + body + (f"\n\n**Notes**\n\n{notes}" if notes else "")


def weak_preview_md(platform: GeniePlatform, *, limit: int = 6) -> str:
    """The topics the *Revise my weak areas* button is about to target."""
    areas = platform.revision.weakest_topics(limit=limit)
    if not areas:
        return (
            "**No weak areas recorded yet.** Submit a test in the Practice tab - this button "
            "then builds a sheet from the topics you actually lost marks in."
        )
    return weak_areas_md(areas)


# ---------------------------------------------------------------------------
# Gradio layout
# ---------------------------------------------------------------------------
def build(
    gr: Any,
    platform: GeniePlatform,
    settings: Any,
    nav: Any | None = None,
    *,
    targets: Mapping[str, Any] | None = None,
    autowire: bool = True,
) -> dict[str, Any]:
    """Create the Revision Hub widgets and return the widget references.

    See :func:`ui.learn.build` for why ``autowire`` exists.
    """
    catalog = platform.catalog()
    gr.Markdown(revision_intro_md())

    with gr.Row():
        deliverable_box = gr.Radio(
            choices=deliverable_choices(),
            value=RevisionDeliverable.FLASH_NOTES.value,
            label="Sheet type",
        )
        subject_box = gr.Dropdown(
            choices=subject_choices(catalog),
            value=(catalog.subjects[0] if catalog.subjects else "physics"),
            label="Subject",
        )
        target_box = gr.Dropdown(
            choices=target_choices(catalog, subject_box.value),
            value=None,
            allow_custom_value=True,
            label="Chapter or topic",
            info="Leave blank to revise the whole subject. Free text works too.",
        )

    with gr.Row():
        generate_btn = gr.Button("Generate sheet", variant="primary", scale=3)
        weak_btn = gr.Button("Revise my weak areas", scale=2)
    status_box = gr.Markdown("_Pick a sheet type and a target, then Generate._")

    sheet_box = gr.Markdown()
    with gr.Accordion("Passages behind this sheet", open=False):
        citations_box = gr.Markdown("_Appears after the first sheet._")

    with gr.Accordion("Your recorded weak areas", open=False):
        weak_box = gr.Markdown(weak_preview_md(platform))
        ask_btn = gr.Button("Ask Genie to explain these")
        ask_md = gr.Markdown()

    refs: dict[str, Any] = {
        "deliverable": deliverable_box,
        "subject": subject_box,
        "target": target_box,
        "generate": generate_btn,
        "weak": weak_btn,
        "status": status_box,
        "sheet": sheet_box,
        "citations": citations_box,
        "weak_preview": weak_box,
        "ask": ask_btn,
        "ask_md": ask_md,
    }
    if autowire:
        wire(gr, platform, refs, nav=nav, targets=targets or {})
    return refs


def wire(
    gr: Any,
    platform: GeniePlatform,
    refs: dict[str, Any],
    *,
    nav: Any | None = None,
    targets: Mapping[str, Any] | None = None,
) -> None:
    """Bind the Revision Hub's controls to :class:`RevisionService`."""
    targets = targets or {}

    def pick_targets(subject: str) -> Any:
        choices = target_choices(platform.catalog(), subject)
        return refresh(choices=choices, value=choices[0][1] if choices else None)

    def make_sheet(deliverable: str, subject: str, target: str) -> list[Any]:
        doc = platform.revision_sheet(deliverable, subject=subject, target=esc(target))
        label = f"{subject.title()} · {esc(target) or 'whole subject'}"
        return [
            f"**Status:** {'done' if doc.ok else 'not generated'} - "
            f"{len(doc.citations)} passage(s), {len(doc.notices)} note(s). Sheets are counted in Progress.",
            sheet_md(doc, label=label),
            citations_md(doc.citations),
            weak_preview_md(platform),
        ]

    def revise_weak(deliverable: str) -> list[Any]:
        doc = platform.revise_weak_areas(deliverable)
        return [
            f"**Status:** {'weak-area sheet built' if doc.ok else 'no weak areas recorded yet'}.",
            sheet_md(doc, label="from your test history"),
            citations_md(doc.citations),
            weak_preview_md(platform),
        ]

    def draft_question(target: str) -> list[Any]:
        focus = esc(target) or "my weakest topics"
        seed = f"Go through {focus} one line at a time, name the trap in each and finish with three MCQs."
        values: list[Any] = [f"**Drafted for Ask Genie:** _{seed}_"]
        if "ask_message" in targets:
            values.append(refresh(value=seed))
        if "ask_mode" in targets:
            values.append(refresh(value="quick_revision"))
        return values + (nav.tail("ask-genie") if nav is not None else [])

    refs["subject"].change(pick_targets, inputs=[refs["subject"]], outputs=[refs["target"]], queue=False)
    sheet_outputs = [refs["status"], refs["sheet"], refs["citations"], refs["weak_preview"]]
    refs["generate"].click(
        make_sheet,
        inputs=[refs["deliverable"], refs["subject"], refs["target"]],
        outputs=sheet_outputs,
    )
    refs["weak"].click(revise_weak, inputs=[refs["deliverable"]], outputs=sheet_outputs)
    ask_outputs = [refs["ask_md"]]
    for name in ("ask_message", "ask_mode"):
        if name in targets:
            ask_outputs.append(targets[name])
    ask_outputs.extend(nav.outputs if nav is not None else [])
    refs["ask"].click(draft_question, inputs=[refs["target"]], outputs=ask_outputs, queue=False)
